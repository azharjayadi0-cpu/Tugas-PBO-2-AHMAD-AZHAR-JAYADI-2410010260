    private void jTabelRegristrasiMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_jTabelRegristrasiMouseClicked
                                                   
        int baris = jTabelRegristrasi.getSelectedRow();
        if (baris != -1) {
            // Mengambil data langsung dari tabel JTable
            String nama = jTabelRegristrasi.getValueAt(baris, 0).toString();
            String noHp = jTabelRegristrasi.getValueAt(baris, 1).toString();
            String kelamin = jTabelRegristrasi.getValueAt(baris, 2).toString();
            String alamat = jTabelRegristrasi.getValueAt(baris, 3).toString();
            // Memasukkan data dari tabel ke text field
            txtNama.setText(nama);
            txtNoHP.setText(noHp);
            cmbKelamin.setSelectedItem(kelamin);
            txtAlamat.setText(alamat);
        }
    }//GEN-LAST:event_jTabelRegristrasiMouseClicked

    private void btDaftarMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_btDaftarMouseClicked
                                
        try {
            String nama = txtNama.getText();
            String kelamin = cmbKelamin.getSelectedItem().toString();
            String alamat = txtAlamat.getText();
            int noHp = Integer.parseInt(txtNoHP.getText()); 
            
            Registrasi_pasien pasienBaru = new Registrasi_pasien();
            pasienBaru.setNamaLengkap(nama);
            pasienBaru.setNoHp(noHp);
            pasienBaru.setJenisKelamin(kelamin);
            pasienBaru.setAlamat(alamat);
            
            daftarPasien.add(pasienBaru);
            tampilRegistrasi_pasien(); 
            
            // Kosongkan form setelah input
            txtNama.setText("");
            txtNoHP.setText("");
            cmbKelamin.setSelectedIndex(0); 
            txtAlamat.setText("");
            txtNama.requestFocus();

        } catch (NumberFormatException e) {
            JOptionPane.showMessageDialog(this, 
                "Nomor HP harus berupa angka!", 
                "Peringatan", 
                JOptionPane.WARNING_MESSAGE);
        }
        // TODO add your handling code here:
    }//GEN-LAST:event_btDaftarMouseClicked

    private void btEditActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btEditActionPerformed
        // TODO add your handling code here:
      int baris = jTabelRegristrasi.getSelectedRow();
        
        if (baris >= 0) {
            try {
                // Ambil objek pasien yang mau diedit berdasarkan baris
                Registrasi_pasien p = daftarPasien.get(baris);
                
                // Ubah nilainya menggunakan Setter
                p.setNamaLengkap(txtNama.getText());
                p.setNoHp(Integer.parseInt(txtNoHP.getText()));
                p.setJenisKelamin(cmbKelamin.getSelectedItem().toString());
                p.setAlamat(txtAlamat.getText());
                
                tampilRegistrasi_pasien(); // Refresh tabel
                
                // Kosongkan form
                txtNama.setText("");
                txtNoHP.setText("");
                txtAlamat.setText("");
                
                JOptionPane.showMessageDialog(this, "Data berhasil diubah!");
            } catch (NumberFormatException e) {
                JOptionPane.showMessageDialog(this, "Nomor HP harus berupa angka!");
            }
        } else {
            JOptionPane.showMessageDialog(this, "Pilih data di tabel terlebih dahulu!");
        }
        
    }//GEN-LAST:event_btEditActionPerformed

    private void bthapusActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_bthapusActionPerformed
        // TODO add your handling code here:
        int baris = jTabelRegristrasi.getSelectedRow();
        
        if (baris >= 0) {
            // Hapus data dari ArrayList berdasarkan indeks (baris)
            daftarPasien.remove(baris);
            tampilRegistrasi_pasien(); // Refresh tabel
            
            // Kosongkan form
            txtNama.setText("");
            txtNoHP.setText("");
            txtAlamat.setText("");
            
            JOptionPane.showMessageDialog(this, "Data berhasil dihapus!");
        } else {
            JOptionPane.showMessageDialog(this, "Pilih data di tabel terlebih dahulu!");
        }
        
    }//GEN-LAST:event_bthapusActionPerformed

