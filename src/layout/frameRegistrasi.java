    // Method Tampil Data
    public void tampilRegistrasi_pasien() {
        DefaultTableModel modelTabel = new DefaultTableModel();
        modelTabel.addColumn("Nama Lengkap");
        modelTabel.addColumn("Nomor HP");
        modelTabel.addColumn("Jenis Kelamin");
        modelTabel.addColumn("Alamat");
        
        // Looping berdasarkan ukuran daftarPasien
        for (int i = 0; i < daftarPasien.size(); i++) {
            Registrasi_pasien pasien = daftarPasien.get(i);
            
            // Panggil method getter dari class Registrasi_pasien
            String nm = pasien.getNamaLengkap();
            int no = pasien.getNoHp();
            String jk = pasien.getJenisKelamin();
            String almt = pasien.getAlamat();
            
            Object[] baris = {nm, no, jk, almt};
            modelTabel.addRow(baris);
        }
        
        jTabelRegristrasi.setModel(modelTabel);
    }
    
    

